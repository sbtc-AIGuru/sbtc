def normalize_btc(text: str) -> list[str]:
    """Exact BTC 5-step normalization."""
    # 1. Unicode NFKC
    text = unicodedata.normalize("NFKC", text)
    # 2. HTML unescape
    text = html.unescape(text)
    # 3. Lowercase
    text = text.lower()
    # 4. Collapse spaces
    text = re.sub(r"\s+", " ", text)
    # 5. Strip
    text = text.strip()
    # 6. Tokenize by whitespace
    return text.split() if text else []


def calculate_lcs(x: list[str], y: list[str]) -> int:
    """Longest Common Subsequence of token lists."""
    m, n = len(x), len(y)
    dp = [[0] * (n + 1) for _ in range(m + 1)]
    for i in range(m):
        for j in range(n):
            if x[i] == y[j]:
                dp[i + 1][j + 1] = dp[i][j] + 1
            else:
                dp[i + 1][j + 1] = max(dp[i + 1][j], dp[i][j + 1])
    return dp[m][n]


class TestViBioMIRComprehensive(unittest.TestCase):
    """Full invariant and end-to-end verification."""

    def test_invariant_1_id_preservation(self):
        """Invariant 1: id must strictly come from parquet 'id' column, never row_index."""
        parquet_path = PROJECT_ROOT / "data/links_corpus.parquet"
        if not parquet_path.exists():
            self.skipTest("links_corpus.parquet missing")

        table = pq.read_table(parquet_path)
        batches = list(load_url_range(parquet_path, 0, 10, batch_size=5))
        records = [r for b in batches for r in b]

        for r in records:
            expected_id = table["id"][r.row_index].as_py()
            expected_url = table["url"][r.row_index].as_py()
            self.assertEqual(r.id, expected_id, f"ID mismatch at row {r.row_index}")
            self.assertEqual(r.url, expected_url, f"URL mismatch at row {r.row_index}")

        # Check row 0 has id=583
        self.assertEqual(records[0].id, 583)
        self.assertEqual(records[0].row_index, 0)

    def test_invariant_2_verbatim_overlap_btc(self):
        """Invariant 2: Cleaned verbatim text must achieve >= 0.40 overlap with ground truth."""
        try:
            from verbatim import clean_to_verbatim
        except ImportError:
            self.skipTest("verbatim.py not implemented yet")

        # Ground truth raw HTML extract
        reference_chunk = (
            "bệnh nhân có thể sử dụng thuốc paracetamol với liều lượng 500mg mỗi 4-6 giờ. "
            "không được tự ý tăng liều để tránh nguy cơ ngộ độc gan cấp tính."
        )

        # Markdown generated by Crawl4AI with links, bold, headers
        crawled_markdown = (
            "### Hướng dẫn sử dụng thuốc\n\n"
            "Bệnh nhân có thể sử dụng [thuốc Paracetamol](https://nhathuoc.vn/paracetamol-500) "
            "với liều lượng **500mg** mỗi 4-6 giờ.\n\n"
            "**Cảnh báo:** Không được tự ý tăng liều để tránh nguy cơ ngộ độc gan cấp tính.\n"
            "| Lưu ý | Giới hạn |\n| --- | --- |\n| Tối đa | 4g/ngày |"
        )

        cleaned_verbatim = clean_to_verbatim(crawled_markdown)

        tokens_c = normalize_btc(cleaned_verbatim)
        tokens_g = normalize_btc(reference_chunk)

        lcs = calculate_lcs(tokens_c, tokens_g)
        overlap = lcs / len(tokens_g)

        self.assertGreaterEqual(
            overlap, 0.40,
            f"Overlap {overlap:.2f} is below BTC 40% threshold! LCS={lcs}, |g|={len(tokens_g)}"
        )
        self.assertAlmostEqual(overlap, 1.0, delta=0.01, msg="Expected 100% tokens of g to be found in c")

    def test_live_crawl_http_mode_fast(self):
        """Test live crawl on sample rows to verify HTTP mode works and outputs clean text."""
        parquet_path = PROJECT_ROOT / "data/links_corpus.parquet"
        if not parquet_path.exists():
            self.skipTest("links_corpus.parquet missing")

        out_path = PROJECT_ROOT / "tests/test_live_out.jsonl"
        if out_path.exists():
            out_path.unlink()

        # Rows 100 to 101: bachmai.gov.vn
        args = argparse.Namespace(
            start=100,
            end=101,
            batch_size=10,
            concurrency=2,
            http_concurrency=4,
            fetch_mode="auto",
            light_browser=True,
            avoid_ads=True,
            browser_recycle_after=500,
            min_free_memory_gb=1.0,
            input=parquet_path,
            output=out_path,
        )

        asyncio.run(run_job(args, out_path))
        self.assertTrue(out_path.exists(), "Output file not created")

        lines = [json.loads(l) for l in out_path.read_text(encoding="utf-8").splitlines()]
        self.assertEqual(len(lines), 2)
        for row in lines:
            self.assertTrue(row.get("success"), f"Crawl failed for row {row.get('row_index')}: {row.get('error')}")
            self.assertTrue(bool(row.get("text")), "Cleaned text is empty")
            # Text should not have markdown link artifacts like [anchor](url)
            self.assertNotRegex(row["text"], r"\[.*?\]\(http.*?\)", "Text still contains markdown links!")


